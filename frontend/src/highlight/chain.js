/**
 * 锁链图形的唯一一份坐标，外加从它生成的两种产物。
 *
 * 这条链有两个用处，要的东西不一样：
 *   底栏回显  —— 要一个 React 组件（highlight/icons.jsx 的 ChainIcon）
 *   鼠标指针  —— 要一段 SVG data URI（CSS 的 cursor: url(...)）
 * 两边各写一遍坐标是迟早要漂的，和 --content-measure、--md-font-ratio
 * 提出来是同一个理由：改了一处忘了另一处，页面不会报错，只是两个地方的
 * 锁链慢慢长得不一样。
 *
 * 这个文件是纯 .js，不带 JSX —— icons.jsx 受 react-refresh 限制只能导出
 * 组件，数据和函数放不进去（和 content/fontScale.js 单开一个文件一样）。
 *
 * ── 图形本身 ─────────────────────────────────────────────
 *
 * 两个沿 45° 对角线扣在一起的菱形环，中间一根横杆穿过两个开口。25×25。
 *
 * 45° 不是把图转过去得到的，是直接排进格子里的：像素画里 45° 是最干净的
 * 斜线，一步一格没有毛刺；用 CSS transform 转的话斜边由抗锯齿画出来，
 * 就不是像素台阶了。
 *
 * 几何参数（照着这些可以重新生成）：
 *   环心 (7,17) 和 (17,7)，连线正好 45°
 *   菱形环带取曼哈顿距离 4..6 三层，斜向厚度 ≈ 2.1 格
 *   开口开在朝着对面那个环的那条边上，切掉轴线两侧 ±2 格
 *   横杆沿轴第 3..7 步，3 格宽
 *
 * 横杆那两个数是调出来的：宽 3 不是 2 —— 2 格宽的斜杆实际厚度只有 1.4 格，
 * 比 2.1 的环带细一圈，看着挂不住；长 5 步正好搭到两侧环带上 —— 短了两端
 * 悬空像浮着根棍子，再长就插进内圈、中间糊成一块。
 *
 * 下面是逐行的横向 run：[x, y, 宽]，高度一律 1 格。
 */
export const CHAIN_RECTS = [
  [17, 1, 1], [16, 2, 3], [15, 3, 5], [14, 4, 3], [18, 4, 3],
  [13, 5, 3], [19, 5, 3], [12, 6, 3], [20, 6, 3], [11, 7, 3],
  [21, 7, 3], [12, 8, 2], [20, 8, 3], [19, 9, 3], [14, 10, 3],
  [18, 10, 3], [7, 11, 1], [13, 11, 7], [6, 12, 3], [12, 12, 3],
  [16, 12, 3], [5, 13, 4], [11, 13, 3], [17, 13, 1], [4, 14, 3],
  [10, 14, 3], [3, 15, 3], [2, 16, 3], [11, 16, 2], [1, 17, 3],
  [11, 17, 3], [2, 18, 3], [10, 18, 3], [3, 19, 3], [9, 19, 3],
  [4, 20, 3], [8, 20, 3], [5, 21, 5], [6, 22, 3], [7, 23, 1],
];

/** viewBox 的边长。正方形：链身铺在对角线上 */
export const CHAIN_VIEWBOX = 25;

/**
 * 独立的 SVG 文本，给 CSS 的 url() 用。
 *
 * 三个地方不能省：
 *   xmlns      —— data URI 里的 SVG 是当独立文档解析的，少了它整张图不显示，
 *                 而且不报错，光标只会悄悄退回 fallback
 *   width/height —— 光标图没有\"父元素宽度\"可继承，只有 viewBox 的话浏览器
 *                 按默认 300×150 渲染，超出光标尺寸上限后同样被丢掉
 *   crispEdges —— 和组件那边一致，保证是像素台阶不是灰边
 */
export function chainSvgMarkup({ px, color }) {
  const rects = CHAIN_RECTS.map(
    ([x, y, w]) => `<rect x="${x}" y="${y}" width="${w}" height="1"/>`
  ).join('');

  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}" ` +
    `viewBox="0 0 ${CHAIN_VIEWBOX} ${CHAIN_VIEWBOX}" shape-rendering="crispEdges" ` +
    `fill="${color}">${rects}</svg>`
  );
}

/**
 * 完整的 cursor 值，含热点和回退。
 *
 * encodeURIComponent 整串编码，不要图省事只转几个字符：# 在 URL 里是片段
 * 分隔符，颜色写 #00ffcc 的话后半截会被当成锚点，图直接废掉。
 *
 * 热点放正中间：这条链没有\"尖\"，放角上反而对不准。
 *
 * 末尾的 pointer 是回退，不能省 —— 浏览器对光标图有尺寸上限（普遍 128px，
 * 各家不一），超了或者取不到就整条声明作废，连手型都没有了。
 */
export function chainCursor({ px = 32, color = '#00ffcc' } = {}) {
  const uri = `data:image/svg+xml,${encodeURIComponent(chainSvgMarkup({ px, color }))}`;
  const hotspot = Math.round(px / 2);
  return `url("${uri}") ${hotspot} ${hotspot}, pointer`;
}
